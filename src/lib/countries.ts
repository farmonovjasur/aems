const DISPLAY_NAMES = Object.fromEntries(
  LANGUAGES.map((locale) => [
    locale,
    new Intl.DisplayNames([locale, DEFAULT_LOCALE], { type: 'region' }),
  ]),
) as Record<Locale, Intl.DisplayNames>

const countryNames = (code: string): Record<Locale, string> =>
  Object.fromEntries(
    LANGUAGES.map((locale) => [locale, DISPLAY_NAMES[locale].of(code) ?? code]),
  ) as Record<Locale, string>

export const COUNTRIES: Country[] = COUNTRY_CODES.map((code) => ({
  code,
  names: countryNames(code),
})).sort((a, b) => a.names[DEFAULT_LOCALE].localeCompare(b.names[DEFAULT_LOCALE], 'en'))

/** I18n til kodi (`uz-UZ`, `ru`, …) → `Locale`. Noma'lum til — `en`. */
export function toLocale(language: string | undefined): Locale {
  const short = (language ?? '').slice(0, 2).toLowerCase()
  return (LANGUAGES as readonly string[]).includes(short) ? (short as Locale) : DEFAULT_LOCALE
}

export function countryName(code: string, locale: Locale): string {
  return COUNTRIES.find((country) => country.code === code)?.names[locale] ?? code
}
